import assert from "node:assert/strict"
import fs from "node:fs"

const deployWorkflow = fs.readFileSync(".github/workflows/test-server-deploy.yml", "utf8")
const rollbackWorkflow = fs.readFileSync(".github/workflows/test-server-rollback.yml", "utf8")
const serverProgram = fs.readFileSync("scripts/test-server-deploy.sh", "utf8")
const backendDeployWorkflow = fs.readFileSync(".github/workflows/test-backend-deploy.yml", "utf8")
const backendRollbackWorkflow = fs.readFileSync(".github/workflows/test-backend-rollback.yml", "utf8")
const backendServerProgram = fs.readFileSync("scripts/test-server-backend-deploy.sh", "utf8")

for (const source of [deployWorkflow, rollbackWorkflow]) {
  assert.match(source, /name: Test/)
  assert.match(source, /https:\/\/test\.muthufarms\.com/)
  assert.match(source, /refs\/heads\/main/)
  assert.match(source, /database_identity=mfms_server_test/)
  assert.match(source, /production_touched=0/)
  assert.doesNotMatch(source, /name: Production/)
  assert.doesNotMatch(source, /https:\/\/muthufarms\.com(?:\/|\s|$)/)
}

assert.match(deployWorkflow, /refs\/heads\/test-release/)
assert.match(deployWorkflow, /deploy-test \$CANDIDATE_REVISION \$EXPECTED_CURRENT_REVISION/)
assert.match(rollbackWorkflow, /rollback-test \$CURRENT_REVISION/)

assert.match(serverProgram, /release_ref="refs\/heads\/test-release"/)
assert.match(serverProgram, /expected_database="mfms_server_test"/)
assert.match(serverProgram, /bridge_container="mfms-test-upstream-bridge"/)
assert.match(serverProgram, /expected_bridge_ip="172\.19\.0\.14"/)
assert.match(serverProgram, /candidate does not contain the live Test baseline/)
assert.match(serverProgram, /a non-Test-frontend container changed/)
assert.match(serverProgram, /TEST_HEALTH_FAILURE_REHEARSAL=PASS/)
assert.equal((serverProgram.match(/mfms_server_prod/g) ?? []).length, 1)
assert.match(serverProgram, /a Production database alias is present in the Test runtime environment/)
assert.doesNotMatch(serverProgram, /nginx -s reload/)
assert.doesNotMatch(serverProgram, /docker (exec|restart) central-nginx/)

for (const source of [backendDeployWorkflow, backendRollbackWorkflow]) {
  assert.match(source, /refs\/heads\/main/)
  assert.match(source, /^\s+name: Test$/m)
  assert.match(source, /https:\/\/test\.muthufarms\.com/)
  assert.match(source, /TEST_SSH_PRIVATE_KEY/)
  assert.match(source, /StrictHostKeyChecking=yes/)
  assert.match(source, /BatchMode=yes/)
  assert.match(source, /PasswordAuthentication=no/)
  assert.match(source, /production_touched=0/)
  assert.doesNotMatch(source, /https:\/\/muthufarms\.com(?:\/|\s|$)/)
}

assert.match(backendDeployWorkflow, /DEPLOY TEST BACKEND ONLY/)
assert.match(backendDeployWorkflow, /deploy-test-backend \$CANDIDATE_REVISION \$EXPECTED_CURRENT_REVISION \$GITHUB_RUN_ID/)
assert.match(backendRollbackWorkflow, /ROLL BACK TEST BACKEND/)
assert.match(backendRollbackWorkflow, /rollback-test-backend \$CURRENT_REVISION \$GITHUB_RUN_ID/)

assert.match(backendServerProgram, /readonly backend_live_container="harvest-api-test"/)
assert.match(backendServerProgram, /readonly frontend_container="mfms-test-web"/)
assert.match(backendServerProgram, /readonly database_name="mfms_server_test"/)
assert.match(backendServerProgram, /readonly test_network="harvest-net"/)
assert.match(backendServerProgram, /readonly live_port="8025"/)
assert.match(backendServerProgram, /readonly candidate_port="8026"/)
assert.match(backendServerProgram, /database-roles\/test-app\.database_url/)
assert.match(backendServerProgram, /parsed\.username != "mfms_test_app"/)
assert.match(backendServerProgram, /deployment_kind == "backend-no-database-change"/)
assert.match(backendServerProgram, /deployment_kind == "backend-with-forward-only-migrations"/)
assert.match(backendServerProgram, /apply_test_migrations\.py/)
assert.match(backendServerProgram, /create_test_database_backup/)
assert.match(backendServerProgram, /database_backup_verified=true/)
assert.match(backendServerProgram, /database_migrations=\$migration_mode/)
assert.match(backendServerProgram, /TEST_BACKEND_DEPLOYMENT=PASS/)
assert.match(backendServerProgram, /TEST_BACKEND_ROLLBACK=PASS/)
assert.match(backendServerProgram, /production_touched=0/)
assert.doesNotMatch(backendServerProgram, /docker\s+compose\b/)
assert.doesNotMatch(backendServerProgram, /\bsudo\b/)
assert.doesNotMatch(backendServerProgram, /nginx\s+-s\s+reload/)
assert.doesNotMatch(backendServerProgram, /crontab\s+-[er]/)

console.log("Test deployment workflow safety checks passed")
